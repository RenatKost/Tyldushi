// Guesses city/region from an organization name (the open ЄДР dump has no addresses).
//
// Built-in regex word boundaries and word classes are ASCII-only, so patterns are written with
// two markers instead: "~" is a Cyrillic-aware word boundary and "@" is "any Cyrillic letter".
const LETTER = "[А-ЯІЇЄҐA-Z'’ʼ]";
const BOUNDARY = `(?:(?<!${LETTER})(?=${LETTER})|(?<=${LETTER})(?!${LETTER}))`;
const cyr = pattern => new RegExp(pattern.replaceAll('~', BOUNDARY).replaceAll('@', LETTER), 'u');

