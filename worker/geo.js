export function guessLocation(name) {
    const upper = String(name || '').toUpperCase();
    const city = CITIES.find(([, re]) => re.test(upper))?.[0] || null;
    const region = REGIONS.find(([, re]) => re.test(upper))?.[0] || null;
    return { city, region };
}

const CITY_NAMES = CITIES.map(([name]) => name);

/** Normalizes a free-text city (from the LLM or a page) to a known spelling where possible. */
export function normalizeCity(value) {
    if (!value) return null;
    const s = String(value).trim().replace(/^(м\.|місто)\s*/i, '').replace(/\s+/g, ' ');
    if (!s || s.length > 60) return null;
    const known = CITY_NAMES.find(c => c.toLowerCase() === s.toLowerCase());
    if (known) return known;
    return s.charAt(0).toUpperCase() + s.slice(1);
}
